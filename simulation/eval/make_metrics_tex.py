"""Emit docs/metrics.tex from the measured results.

Every number quoted in the technical report is defined here as a macro read
straight from the result files, so the document cannot drift out of step with
the experiments. Re-running the evaluation and rebuilding the PDF is enough to
update the report.
"""
import json
import os

import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LOG = f"{ROOT}/results/logs"
DOCS = os.path.join(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))), "docs")
os.makedirs(DOCS, exist_ok=True)


def load(name, default=None):
    p = f"{LOG}/{name}"
    if not os.path.exists(p):
        return default
    with open(p) as fh:
        return json.load(fh)


mission = load("mission_varuna_s1.json", {})
mapping = load("mapping_metrics.json", {})
detect = load("detection_metrics.json", {})
sim2real = load("sim2real_metrics.json", {})
synth = load("synth_transfer_metrics.json", {})
train = None
p = f"{ROOT}/ml/models/train_metrics.json"
if os.path.exists(p):
    train = json.load(open(p))

lines = ["% Generated by eval/make_metrics_tex.py. Do not edit by hand.", ""]


def cmd(name, value, fmt="{}"):
    # LaTeX control sequences are letters only. Catch this at generation time
    # rather than as an obscure failure during the document build.
    assert name.isalpha(), f"macro name {name!r} must be letters only"
    if value is None:
        lines.append(f"\\newcommand{{\\{name}}}{{\\textit{{n/a}}}}")
    else:
        lines.append(f"\\newcommand{{\\{name}}}{{{fmt.format(value)}}}")


# ---------------------------------------------------------------- mission
cmd("misDuration", mission.get("duration"), "{:.0f}")
cmd("misDurationMin", (mission.get("duration") or 0) / 60.0, "{:.1f}")
cmd("misPath", mission.get("path_length"), "{:.0f}")
cmd("misCoverage", (mission.get("coverage") or 0) * 100, "{:.1f}")
cmd("misNavMean", mission.get("nav_error_mean"), "{:.2f}")
cmd("misNavMax", mission.get("nav_error_max"), "{:.2f}")
cmd("misNavFinal", mission.get("nav_error_final"), "{:.2f}")
cmd("misSigma", mission.get("sigma_final"), "{:.2f}")
cmd("misDvl", (mission.get("dvl_availability") or 0) * 100, "{:.1f}")
cmd("misSoundings", mission.get("soundings"), "{:,}")
cmd("misPings", mission.get("pings"), "{}")
cmd("misEnvelope", mission.get("max_holdable_current"), "{:.2f}")
cmd("siteCurrent", mission.get("site_surface_current"), "{:.1f}")
cmd("siteSSC", mission.get("ssc_g_per_l"), "{:.1f}")
cmd("misWall", mission.get("wall_clock_s"), "{:.0f}")

# Navigation drift as a fraction of distance travelled, the standard measure.
if mission.get("path_length"):
    cmd("misDriftPct",
        100.0 * (mission.get("nav_error_final") or 0) / mission["path_length"],
        "{:.2f}")
else:
    cmd("misDriftPct", None)

# ---------------------------------------------------------------- scour
# LaTeX control sequences cannot contain digits, so pier identifiers are
# spelled out: P2 becomes PierTwo.
DIGITS = {"0": "Zero", "1": "One", "2": "Two", "3": "Three", "4": "Four",
          "5": "Five", "6": "Six", "7": "Seven", "8": "Eight", "9": "Nine"}


def spell(s):
    return "".join(DIGITS.get(ch, ch) for ch in s)


sc = mission.get("scour", {}) or {}
for k, v in sc.items():
    tag = spell(k.replace("P", "Pier"))
    if not v:
        continue
    cmd(f"scour{tag}Depth", v.get("max_depth"), "{:.2f}")
    cmd(f"scour{tag}DepthTruth", v.get("truth_depth"), "{:.2f}")
    cmd(f"scour{tag}Vol", v.get("volume"), "{:.0f}")
    cmd(f"scour{tag}VolTruth", v.get("truth_volume"), "{:.0f}")
    if v.get("truth_depth"):
        cmd(f"scour{tag}Rec", 100 * v["max_depth"] / v["truth_depth"], "{:.0f}")

depths = [(v["max_depth"], v["truth_depth"]) for v in sc.values() if v]
if depths:
    err = [abs(a - b) for a, b in depths]
    cmd("scourMeanAbsErr", float(np.mean(err)), "{:.2f}")
    cmd("scourMeanRec",
        float(np.mean([100 * a / b for a, b in depths])), "{:.0f}")

# ---------------------------------------------------------------- mapping
cmd("mapRmse", mapping.get("map_rmse"), "{:.2f}")
cmd("mapBias", mapping.get("map_bias"), "{:+.2f}")

# ---------------------------------------------------------------- detection
cmd("detClusters", detect.get("clusters"), "{}")
cmd("detPrimary", detect.get("primary_detected"), "{}")
cmd("detPrimaryTotal", detect.get("primary_total"), "{}")
cmd("detMeanErr", detect.get("primary_mean_error_m"), "{:.2f}")
cmd("detMaxErr", detect.get("primary_max_error_m"), "{:.2f}")
bc = detect.get("by_class", {}) or {}
for c, v in bc.items():
    tag = spell("".join(w.capitalize() for w in c.split("_")))
    cmd(f"det{tag}Hit", v.get("detected"), "{}")
    cmd(f"det{tag}Tot", v.get("total"), "{}")

# ---------------------------------------------------------------- perception
if train:
    for split in ("val", "test"):
        s = train.get(split, {})
        tag = split.capitalize()
        cmd(f"yolo{tag}MapFifty", s.get("mAP50", 0) * 100, "{:.1f}")
        cmd(f"yolo{tag}Map", s.get("mAP50_95", 0) * 100, "{:.1f}")
        cmd(f"yolo{tag}P", s.get("precision", 0) * 100, "{:.1f}")
        cmd(f"yolo{tag}R", s.get("recall", 0) * 100, "{:.1f}")
    cmd("yoloClasses", len(train.get("classes", {})), "{}")

cmd("simRealRecall", (sim2real.get("recall") or 0) * 100, "{:.1f}")
cmd("simRealScenes", sim2real.get("scenes"), "{}")
cmd("simRealInstances", sim2real.get("instances"), "{}")
cmd("simRealConfReal", sim2real.get("mean_conf_real"), "{:.2f}")

if synth:
    cmd("synthMapFifty", (synth.get("mAP50") or 0) * 100, "{:.1f}")
    cmd("synthMap", (synth.get("mAP50_95") or 0) * 100, "{:.1f}")
    cmd("synthP", (synth.get("precision") or 0) * 100, "{:.1f}")
    cmd("synthR", (synth.get("recall") or 0) * 100, "{:.1f}")
    cmd("synthTrain", synth.get("n_train"), "{}")
    # The same model measured on its own simulated validation split. This
    # separates "the simulator produces learnable, correctly labelled data"
    # from "that learning transfers to real sonar", which are different claims.
    cmd("synthSelfMapFifty", (synth.get("sim_val_mAP50") or 0) * 100, "{:.1f}")
    cmd("synthSelfMap", (synth.get("sim_val_mAP50_95") or 0) * 100, "{:.1f}")
else:
    for n in ("synthMapFifty", "synthMap", "synthP", "synthR", "synthTrain",
              "synthSelfMapFifty", "synthSelfMap"):
        cmd(n, None)

# ---------------------------------------------------------------- cross domain
xd = load("cross_domain_metrics.json", None)
if xd:
    for key, tag in (("real_self", "RealSelf"), ("sim_self", "SimSelf"),
                     ("real_to_sim", "RealToSim"), ("sim_to_real", "SimToReal")):
        v = xd.get(key) or {}
        cmd(f"xd{tag}Fifty", (v.get("mAP50") or 0) * 100, "{:.1f}")
        cmd(f"xd{tag}", (v.get("mAP50_95") or 0) * 100, "{:.1f}")
else:
    for tag in ("RealSelf", "SimSelf", "RealToSim", "SimToReal"):
        cmd(f"xd{tag}Fifty", None)
        cmd(f"xd{tag}", None)

# ---------------------------------------------------------------- repeatability
rep = load("repeatability.json", None)
if rep:
    cmd("repRuns", rep.get("runs"), "{}")
    cmd("repCompleted", rep.get("missions_completed"), "{}")
    cmd("repAllTargets", rep.get("all_targets_found"), "{}")
    for key, tag in (("coverage", "Cover"), ("nav_mean", "NavMean"),
                     ("nav_max", "NavMax"), ("dvl", "Dvl"),
                     ("map_rmse", "MapRmse"), ("det_err", "DetErr"),
                     ("scour_rec", "ScourRec")):
        v = rep.get(key) or {}
        dp = 1 if key in ("coverage", "dvl", "scour_rec") else (
            3 if key in ("nav_mean", "nav_max", "map_rmse") else 2)
        cmd(f"rep{tag}Mean", v.get("mean"), "{:." + str(dp) + "f}")
        cmd(f"rep{tag}Std", v.get("std"), "{:." + str(dp) + "f}")
else:
    for n in ("repRuns", "repCompleted", "repAllTargets"):
        cmd(n, None)
    for tag in ("Cover", "NavMean", "NavMax", "Dvl", "MapRmse", "DetErr",
                "ScourRec"):
        cmd(f"rep{tag}Mean", None)
        cmd(f"rep{tag}Std", None)

# ---------------------------------------------------------------- data efficiency
de = load("data_efficiency.json", None)
if de:
    best_gain, best_n = None, None
    for row in de:
        n = row["n_real"]
        tag = spell(f"N{n}") + row["arm"].capitalize()
        cmd(f"de{tag}", row["mAP50"] * 100, "{:.1f}")
    for n in sorted({r["n_real"] for r in de}):
        c = next((r for r in de if r["n_real"] == n and r["arm"] == "coco"), None)
        s2 = next((r for r in de if r["n_real"] == n and r["arm"] == "sim"), None)
        if c and s2:
            g = (s2["mAP50"] - c["mAP50"]) * 100
            if best_gain is None or g > best_gain:
                best_gain, best_n = g, n
    cmd("deBestGain", best_gain, "{:+.1f}")
    cmd("deBestN", best_n, "{}")
else:
    for n in ("deBestGain", "deBestN"):
        cmd(n, None)

with open(f"{DOCS}/metrics.tex", "w") as fh:
    fh.write("\n".join(lines) + "\n")
print(f"wrote {DOCS}/metrics.tex with {len(lines)-2} macros")
for l in lines[2:]:
    print("  ", l)
