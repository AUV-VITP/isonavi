"""Emit docs/metrics.tex from the measured results.

Every number quoted in the technical report is defined here as a macro read
straight from the result files, so the document cannot drift out of step with
the experiments. Re-running the evaluation and rebuilding the PDF is enough to
update the report.
"""
import json
import os

import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LOG = f"{ROOT}/results/logs"
DOCS = os.path.join(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))), "docs")
os.makedirs(DOCS, exist_ok=True)


def load(name, default=None):
    p = f"{LOG}/{name}"
    if not os.path.exists(p):
        return default
    with open(p) as fh:
        return json.load(fh)


mission = load("mission_varuna_s1.json", {})
mapping = load("mapping_metrics.json", {})
detect = load("detection_metrics.json", {})
sim2real = load("sim2real_metrics.json", {})
synth = load("synth_transfer_metrics.json", {})
train = None
p = f"{ROOT}/ml/models/train_metrics.json"
if os.path.exists(p):
    train = json.load(open(p))

lines = ["% Generated by eval/make_metrics_tex.py. Do not edit by hand.", ""]


def cmd(name, value, fmt="{}"):
    # LaTeX control sequences are letters only. Catch this at generation time
    # rather than as an obscure failure during the document build.
    assert name.isalpha(), f"macro name {name!r} must be letters only"
    if value is None:
        lines.append(f"\\newcommand{{\\{name}}}{{\\textit{{n/a}}}}")
    else:
        lines.append(f"\\newcommand{{\\{name}}}{{{fmt.format(value)}}}")


# ---------------------------------------------------------------- mission
cmd("misDuration", mission.get("duration"), "{:.0f}")
cmd("misDurationMin", (mission.get("duration") or 0) / 60.0, "{:.1f}")
cmd("misPath", mission.get("path_length"), "{:.0f}")
cmd("misCoverage", (mission.get("coverage") or 0) * 100, "{:.1f}")
cmd("misNavMean", mission.get("nav_error_mean"), "{:.2f}")
cmd("misNavMax", mission.get("nav_error_max"), "{:.2f}")
cmd("misNavFinal", mission.get("nav_error_final"), "{:.2f}")
cmd("misSigma", mission.get("sigma_final"), "{:.2f}")
cmd("misDvl", (mission.get("dvl_availability") or 0) * 100, "{:.1f}")
cmd("misSoundings", mission.get("soundings"), "{:,}")
cmd("misPings", mission.get("pings"), "{}")
cmd("misEnvelope", mission.get("max_holdable_current"), "{:.2f}")
cmd("siteCurrent", mission.get("site_surface_current"), "{:.1f}")
cmd("siteSSC", mission.get("ssc_g_per_l"), "{:.1f}")
cmd("misWall", mission.get("wall_clock_s"), "{:.0f}")

# Navigation drift as a fraction of distance travelled, the standard measure.
if mission.get("path_length"):
    cmd("misDriftPct",
        100.0 * (mission.get("nav_error_final") or 0) / mission["path_length"],
        "{:.2f}")
else:
    cmd("misDriftPct", None)

# ---------------------------------------------------------------- scour
# LaTeX control sequences cannot contain digits, so pier identifiers are
# spelled out: P2 becomes PierTwo.
DIGITS = {"0": "Zero", "1": "One", "2": "Two", "3": "Three", "4": "Four",
          "5": "Five", "6": "Six", "7": "Seven", "8": "Eight", "9": "Nine"}


def spell(s):
    return "".join(DIGITS.get(ch, ch) for ch in s)


sc = mission.get("scour", {}) or {}
for k, v in sc.items():
    tag = spell(k.replace("P", "Pier"))
    if not v:
        continue
    cmd(f"scour{tag}Depth", v.get("max_depth"), "{:.2f}")
    cmd(f"scour{tag}DepthTruth", v.get("truth_depth"), "{:.2f}")
    cmd(f"scour{tag}Vol", v.get("volume"), "{:.0f}")
    cmd(f"scour{tag}VolTruth", v.get("truth_volume"), "{:.0f}")
    if v.get("truth_depth"):
        cmd(f"scour{tag}Rec", 100 * v["max_depth"] / v["truth_depth"], "{:.0f}")

depths = [(v["max_depth"], v["truth_depth"]) for v in sc.values() if v]
if depths:
    err = [abs(a - b) for a, b in depths]
    cmd("scourMeanAbsErr", float(np.mean(err)), "{:.2f}")
    cmd("scourMeanRec",
        float(np.mean([100 * a / b for a, b in depths])), "{:.0f}")

# ---------------------------------------------------------------- mapping
cmd("mapRmse", mapping.get("map_rmse"), "{:.2f}")
cmd("mapBias", mapping.get("map_bias"), "{:+.2f}")

# ---------------------------------------------------------------- detection
cmd("detClusters", detect.get("clusters"), "{}")
cmd("detPrimary", detect.get("primary_detected"), "{}")
cmd("detPrimaryTotal", detect.get("primary_total"), "{}")
cmd("detMeanErr", detect.get("primary_mean_error_m"), "{:.2f}")
cmd("detMaxErr", detect.get("primary_max_error_m"), "{:.2f}")
bc = detect.get("by_class", {}) or {}
for c, v in bc.items():
    tag = spell("".join(w.capitalize() for w in c.split("_")))
    cmd(f"det{tag}Hit", v.get("detected"), "{}")
    cmd(f"det{tag}Tot", v.get("total"), "{}")

# ---------------------------------------------------------------- perception
if train:
    for split in ("val", "test"):
        s = train.get(split, {})
        tag = split.capitalize()
        cmd(f"yolo{tag}MapFifty", s.get("mAP50", 0) * 100, "{:.1f}")
        cmd(f"yolo{tag}Map", s.get("mAP50_95", 0) * 100, "{:.1f}")
        cmd(f"yolo{tag}P", s.get("precision", 0) * 100, "{:.1f}")
        cmd(f"yolo{tag}R", s.get("recall", 0) * 100, "{:.1f}")
    cmd("yoloClasses", len(train.get("classes", {})), "{}")

cmd("simRealRecall", (sim2real.get("recall") or 0) * 100, "{:.1f}")
cmd("simRealScenes", sim2real.get("scenes"), "{}")
cmd("simRealInstances", sim2real.get("instances"), "{}")
cmd("simRealConfReal", sim2real.get("mean_conf_real"), "{:.2f}")

if synth:
    cmd("synthMapFifty", (synth.get("mAP50") or 0) * 100, "{:.1f}")
    cmd("synthMap", (synth.get("mAP50_95") or 0) * 100, "{:.1f}")
    cmd("synthP", (synth.get("precision") or 0) * 100, "{:.1f}")
    cmd("synthR", (synth.get("recall") or 0) * 100, "{:.1f}")
    cmd("synthTrain", synth.get("n_train"), "{}")
    # The same model measured on its own simulated validation split. This
    # separates "the simulator produces learnable, correctly labelled data"
    # from "that learning transfers to real sonar", which are different claims.
    cmd("synthSelfMapFifty", (synth.get("sim_val_mAP50") or 0) * 100, "{:.1f}")
    cmd("synthSelfMap", (synth.get("sim_val_mAP50_95") or 0) * 100, "{:.1f}")
else:
    for n in ("synthMapFifty", "synthMap", "synthP", "synthR", "synthTrain",
              "synthSelfMapFifty", "synthSelfMap"):
        cmd(n, None)

# ---------------------------------------------------------------- hardware in the loop
hil = load("hil_metrics.json", None)
if hil:
    cmd("hilNavMean", hil.get("hil_nav_mean"), "{:.3f}")
    cmd("hilNavMax", hil.get("hil_nav_max"), "{:.3f}")
    cmd("hilTicks", hil.get("hil_ticks"), "{:,}")
    cmd("hilSimTime", hil.get("hil_sim_time"), "{:.0f}")
    cmd("hilCrc", hil.get("hil_crc"), "{}")
    cmd("boardComputeMean", hil.get("board_compute_mean"), "{:.1f}")
    cmd("boardComputeNn", hil.get("board_compute_p99"), "{:.1f}")
    cmd("boardWaitMean", hil.get("board_wait_mean"), "{:.1f}")
    cmd("boardBudget", hil.get("board_budget"), "{:.0f}")
    cmd("boardMargin", hil.get("board_margin"), "{:.1f}")
    cmd("boardLoopNn", hil.get("board_loop_p99"), "{:.1f}")
    cmd("espSent", hil.get("esp_pwm_sent"), "{:,}")
    cmd("espEchoes", hil.get("esp_echoes"), "{:,}")
    cmd("espMatched", hil.get("esp_matched"), "{:,}")
    cmd("espMismatch", hil.get("esp_mismatches"), "{}")
    cmd("espLag", hil.get("esp_lag_mean"), "{:.1f}")
    cmd("espMs", hil.get("esp_ms_mean"), "{:.1f}")
    cmd("espMsNn", hil.get("esp_ms_p99"), "{:.1f}")
else:
    for n in ("hilNavMean", "hilNavMax", "hilTicks", "hilSimTime", "hilCrc",
              "boardComputeMean", "boardComputeNn", "boardWaitMean",
              "boardBudget", "boardMargin"):
        cmd(n, None)

# ---------------------------------------------------------------- vehicle cad
# Read straight from the CAD solve so the drawing and the document cannot
# disagree about the vehicle.
_cadp = os.path.join(os.path.dirname(ROOT), "cad", "varuna_cad_params.json")
cad = json.load(open(_cadp)) if os.path.exists(_cadp) else None
_CAD = (("cadLength", "hull_length_mm", "{:.0f}"),
        ("cadDia", "hull_diameter_mm", "{:.0f}"),
        ("cadSlender", "hull_slenderness", "{:.1f}"),
        ("cadMidbody", "midbody_length_mm", "{:.0f}"),
        ("cadWetted", "wetted_area_m2", "{:.3f}"),
        ("cadSkin", "skin_thickness_mm", "{:.0f}"),
        ("cadVolume", "displaced_volume_m3", "{:.4f}"),
        ("cadHullVolume", "hull_volume_m3", "{:.4f}"),
        ("cadMass", "mass_kg", "{:.1f}"),
        ("cadNetBuoy", "net_buoyancy_N", "{:.2f}"),
        ("cadBG", "bg_mm", "{:.1f}"),
        ("cadBallast", "ballast_kg", "{:.1f}"),
        ("cadParts", "n_parts", "{}"))
for _name, _key, _fmt in _CAD:
    cmd(_name, cad.get(_key) if cad else None, _fmt)
cmd("cadVolErr", abs(cad.get("hull_volume_error_pct", 0.0)) if cad else None,
    "{:.3f}")

# The same two dimensions in metres. The comparison table sets this vehicle
# against two commercial ones quoted in metres, and converting by hand in the
# document would put a copy of a generated number back into the source.
for _n, _k in (("cadLengthM", "hull_length_mm"), ("cadDiaM",
                                                  "hull_diameter_mm")):
    _v = cad.get(_k) if cad else None
    cmd(_n, _v / 1000.0 if _v is not None else None, "{:.2f}")
# The stability separation the dynamics model assumed before the CAD was built.
cmd("cadBGAssumed", 85.0, "{:.0f}")

# ---------------------------------------------------------------- pressure hull
_stp = os.path.join(os.path.dirname(ROOT), "cad", "varuna_structures.json")
struct = json.load(open(_stp)) if os.path.exists(_stp) else None
_ST = (("structDepth", "design_depth_m", "{:.0f}"),
       ("structPressure", "design_pressure_MPa", "{:.3f}"),
       ("structSkin", "skin_mm", "{:.0f}"),
       ("structFrameSpacing", "frame_spacing_mm", "{:.0f}"),
       ("structHoop", "hoop_stress_MPa", "{:.1f}"),
       ("structStrength", "laminate_strength_MPa", "{:.0f}"),
       ("structSfYield", "sf_yield", "{:.1f}"),
       ("structCollapseUn", "collapse_depth_unstiffened_m", "{:.0f}"),
       ("structCollapseSt", "collapse_depth_stiffened_m", "{:.0f}"),
       ("structSfBuckle", "sf_buckling", "{:.1f}"),
       ("structFrameGain", "frame_gain", "{:.1f}"),
       ("structPylonArm", "pylon_arm_mm", "{:.0f}"),
       ("structPylonStress", "pylon_stress_MPa", "{:.1f}"),
       ("structPylonSf", "pylon_sf", "{:.0f}"))
for _n, _k, _f in _ST:
    cmd(_n, struct.get(_k) if struct else None, _f)

# ---------------------------------------------------------------- hydrodynamics
_hyp = os.path.join(os.path.dirname(ROOT), "cad", "varuna_hydro.json")
hydro = json.load(open(_hyp)) if os.path.exists(_hyp) else None
_HY = (("hydroCf", "cf", "{:.5f}"),
       ("hydroForm", "form_factor", "{:.3f}"),
       ("hydroDragHull", "drag_hull", "{:.1f}"),
       ("hydroDragApp", "drag_appendages", "{:.1f}"),
       ("hydroDragTotal", "drag_total", "{:.1f}"),
       ("hydroDragSim", "drag_sim", "{:.0f}"),
       ("hydroDragRatio", "drag_ratio", "{:.2f}"),
       ("hydroAppShare", "appendage_share_pct", "{:.0f}"),
       ("hydroAddAxial", "added_axial_total", "{:.1f}"),
       ("hydroAddLateral", "added_lateral_hull", "{:.1f}"),
       ("hydroEnvSim", "envelope_sim", "{:.2f}"),
       ("hydroEnvCad", "envelope_cad", "{:.2f}"),
       ("hydroMargin", "margin_cad", "{:.2f}"),
       ("hydroSlender", "slenderness", "{:.2f}"))
for _n, _k, _f in _HY:
    cmd(_n, hydro.get(_k) if hydro else None, _f)

# ---------------------------------------------------------------- bill of materials
_bmp = os.path.join(os.path.dirname(ROOT), "cad", "varuna_bom.json")
bom = json.load(open(_bmp)) if os.path.exists(_bmp) else None
_BM = (("bomTotal", "total_usd", "{:,.0f}"),
       ("bomLakh", "total_lakh_inr", "{:.1f}"),
       ("bomAcoustics", "acoustics_usd", "{:,.0f}"),
       ("bomAcousticsPct", "acoustics_pct", "{:.0f}"),
       ("bomRest", "non_acoustics_usd", "{:.0f}"),
       ("bomRate", "usd_inr", "{:.0f}"))
for _n, _k, _f in _BM:
    cmd(_n, bom.get(_k) if bom else None, _f)

# ---------------------------------------------------------------- energy
_enp = os.path.join(os.path.dirname(ROOT), "cad", "varuna_energy.json")
energy = json.load(open(_enp)) if os.path.exists(_enp) else None
_EN = (("enBattery", "battery_wh", "{:.0f}"),
       ("enHotel", "hotel_w", "{:.0f}"),
       ("enMissionWh", "mission_wh", "{:.0f}"),
       ("enMissionPct", "mission_pct", "{:.0f}"),
       ("enMissions", "missions_per_charge", "{:.1f}"),
       ("enPropMean", "p_prop_mean", "{:.0f}"),
       ("enPropPeak", "p_prop_peak", "{:.0f}"),
       ("enTotalMean", "p_total_mean", "{:.0f}"),
       ("enHoursSite", "hours_at_site_current", "{:.1f}"),
       ("enHoursCalm", "hours_calm", "{:.1f}"),
       ("enEta", "eta", "{:.2f}"))
for _n, _k, _f in _EN:
    cmd(_n, energy.get(_k) if energy else None, _f)

# ---------------------------------------------------------------- redundancy
_rdp = os.path.join(os.path.dirname(ROOT), "cad", "varuna_redundancy.json")
red = json.load(open(_rdp)) if os.path.exists(_rdp) else None
_RD = (("redSurgeIntact", "surge_intact", "{:.0f}"),
       ("redEnvIntact", "envelope_intact", "{:.2f}"),
       ("redNeed", "need_n", "{:.0f}"),
       ("redSingleOk", "single_ok", "{}"),
       ("redPairsOk", "pairs_ok", "{}"),
       ("redPairsTotal", "pairs_total", "{}"),
       ("redWorstPct", "worst_single_pct", "{:.0f}"),
       ("redDegraded", "degraded_best_ms", "{:.2f}"),
       ("redThrustNeeded", "thrust_for_tolerance_n", "{:.0f}"))
for _n, _k, _f in _RD:
    cmd(_n, red.get(_k) if red else None, _f)
cmd("redWorstSurge",
    red["worst_single"]["surge"] if red else None, "{:.0f}")
cmd("redWorstEnv",
    red["worst_single"]["envelope"] if red else None, "{:.2f}")
cmd("redHeaveIntact", red.get("heave_intact") if red else None, "{:.0f}")

# ---------------------------------------------------------------- detection quality
_rep = load("repeatability.json", {}) or {}
cmd("detContacts", _rep.get("contacts_per_run"), "{:.1f}")
cmd("detFalseAlarms", _rep.get("false_alarms_per_run"), "{:.1f}")
cmd("detFalseAlarmsSd", _rep.get("false_alarms_std"), "{:.1f}")
cmd("detFalsePerHa", _rep.get("false_alarms_per_hectare"), "{:.1f}")
cmd("detSurveyHa", _rep.get("survey_area_ha"), "{:.2f}")
cmd("detAllFound", _rep.get("all_targets_found"), "{}")
cmd("detRuns", _rep.get("runs"), "{}")

# ---------------------------------------------------------------- cross domain
xd = load("cross_domain_metrics.json", None)
if xd:
    for key, tag in (("real_self", "RealSelf"), ("sim_self", "SimSelf"),
                     ("real_to_sim", "RealToSim"), ("sim_to_real", "SimToReal")):
        v = xd.get(key) or {}
        cmd(f"xd{tag}Fifty", (v.get("mAP50") or 0) * 100, "{:.1f}")
        cmd(f"xd{tag}", (v.get("mAP50_95") or 0) * 100, "{:.1f}")
else:
    for tag in ("RealSelf", "SimSelf", "RealToSim", "SimToReal"):
        cmd(f"xd{tag}Fifty", None)
        cmd(f"xd{tag}", None)

# ---------------------------------------------------------------- repeatability
rep = load("repeatability.json", None)
if rep:
    cmd("repRuns", rep.get("runs"), "{}")
    cmd("repCompleted", rep.get("missions_completed"), "{}")
    cmd("repAllTargets", rep.get("all_targets_found"), "{}")
    for key, tag in (("coverage", "Cover"), ("nav_mean", "NavMean"),
                     ("nav_max", "NavMax"), ("dvl", "Dvl"),
                     ("map_rmse", "MapRmse"), ("det_err", "DetErr"),
                     ("scour_rec", "ScourRec")):
        v = rep.get(key) or {}
        dp = 1 if key in ("coverage", "dvl", "scour_rec") else (
            3 if key in ("nav_mean", "nav_max", "map_rmse") else 2)
        cmd(f"rep{tag}Mean", v.get("mean"), "{:." + str(dp) + "f}")
        cmd(f"rep{tag}Std", v.get("std"), "{:." + str(dp) + "f}")
else:
    for n in ("repRuns", "repCompleted", "repAllTargets"):
        cmd(n, None)
    for tag in ("Cover", "NavMean", "NavMax", "Dvl", "MapRmse", "DetErr",
                "ScourRec"):
        cmd(f"rep{tag}Mean", None)
        cmd(f"rep{tag}Std", None)

# ---------------------------------------------------------------- data efficiency
de = load("data_efficiency.json", None)
if de:
    best_gain, best_n = None, None
    for row in de:
        n = row["n_real"]
        tag = spell(f"N{n}") + row["arm"].capitalize()
        cmd(f"de{tag}", row["mAP50"] * 100, "{:.1f}")
    for n in sorted({r["n_real"] for r in de}):
        c = next((r for r in de if r["n_real"] == n and r["arm"] == "coco"), None)
        s2 = next((r for r in de if r["n_real"] == n and r["arm"] == "sim"), None)
        if c and s2:
            g = (s2["mAP50"] - c["mAP50"]) * 100
            # The difference column of the table is arithmetic on the pair
            # above, so it is generated too rather than worked out by hand.
            cmd(f"deDiff{spell(f'N{n}')}", g, "{:+.1f}")
            if best_gain is None or g > best_gain:
                best_gain, best_n = g, n
    cmd("deBestGain", best_gain, "{:+.1f}")
    cmd("deBestN", best_n, "{}")
else:
    for n in ("deBestGain", "deBestN"):
        cmd(n, None)
    for n in (40, 80, 160, 320, 640):
        cmd(f"deDiff{spell(f'N{n}')}", None)

with open(f"{DOCS}/metrics.tex", "w") as fh:
    fh.write("\n".join(lines) + "\n")
print(f"wrote {DOCS}/metrics.tex with {len(lines)-2} macros")
for l in lines[2:]:
    print("  ", l)
